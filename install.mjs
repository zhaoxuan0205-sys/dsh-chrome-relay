#!/usr/bin/env node
// Register this bundle in a DSH profile and generate the local launcher.
// Machine-specific files are written under ~/.dsh; nothing here is committed.
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const PKG_DIR = path.dirname(fileURLToPath(import.meta.url))
const HOME = os.homedir()
const argv = process.argv.slice(2)
const argOf = (k, d) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : d }

const PROFILE = argOf('--profile', path.join(HOME, '.dsh/profiles/desktop'))
const LAUNCHER = path.join(HOME, '.dsh/bin/browser-bridge-launch.sh')
const OUT_DIR = path.join(HOME, '.dsh/browser-output')
const CWD = argOf('--cwd', HOME)

const PATCH = [
  '# Generated by dsh-chrome-relay install.mjs — local paths, do not commit.',
  '- insert:',
  '    - id: mcp-browser-bridge',
  '      name: "@deepseek-ai/dsh-mcp-client"',
  '      config:',
  '        serverName: browser',
  '        transport: stdio',
  '        command: "/bin/sh"',
  '        args:',
  '          - "' + LAUNCHER + '"',
  '          - "--extension"',
  '          - "--no-webmcp"',
  '          - "--codegen"',
  '          - "none"',
  '          - "--redact-url-params"',
  '          - "token,access_token,id_token,code,authorization,api_key"',
  '          - "--output-dir"',
  '          - "' + OUT_DIR + '"',
  '        cwd: "' + CWD + '"',
  '        toolCallTimeoutMs: 120000',
  ''
].join('\n')

const stamp = () => new Date().toISOString().replace(/[:.]/g, '-')
const backup = (f) => { if (fs.existsSync(f)) { const d = f + '.bak-' + stamp(); fs.copyFileSync(f, d); return d } return null }

function findCli() {
  const explicit = argOf('--cli', process.env.PLAYWRIGHT_MCP_CLI)
  if (explicit) {
    if (!fs.existsSync(explicit)) throw new Error('--cli path does not exist: ' + explicit)
    return explicit
  }
  for (const root of [PKG_DIR, process.cwd(), PROFILE]) {
    try {
      const require = createRequire(path.join(root, 'noop.js'))
      return require.resolve('@playwright/mcp/cli.js')
    } catch {}
  }
  throw new Error('Cannot find @playwright/mcp. Run "pnpm add @playwright/mcp@0.0.84 --ignore-scripts" first, or pass --cli <path>.')
}

const cli = findCli()
fs.mkdirSync(path.dirname(LAUNCHER), { recursive: true })
fs.mkdirSync(OUT_DIR, { recursive: true })

const launcher = [
  '#!/bin/sh',
  '# Generated by dsh-chrome-relay install.mjs',
  '# No credential is read from disk; the Playwright extension asks the user',
  '# to pick the tab the agent may control. Set PLAYWRIGHT_MCP_EXTENSION_TOKEN',
  '# in the environment yourself if you really want to skip that dialog.',
  'NODE="' + process.execPath + '"',
  'CLI="' + cli + '"',
  'exec "$NODE" "$CLI" "$@"',
  ''
].join('\n')
fs.writeFileSync(LAUNCHER, launcher, { mode: 0o700 })

fs.writeFileSync(path.join(PKG_DIR, 'cordis.patch.yml'), PATCH)

const pkgPath = path.join(PROFILE, 'package.json')
if (!fs.existsSync(pkgPath)) throw new Error('No DSH profile at ' + PROFILE + ' (pass --profile <dir>)')
const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'))
const pkgBackup = backup(pkgPath)
pkg.dependencies = pkg.dependencies || {}
pkg.dependencies['dsh-chrome-relay'] = 'link:' + PKG_DIR
pkg.dsh = pkg.dsh || {}
pkg.dsh.profile = pkg.dsh.profile || {}
const bundles = (pkg.dsh.profile.bundles = pkg.dsh.profile.bundles || [])
if (!bundles.includes('dsh-chrome-relay')) bundles.push('dsh-chrome-relay')
fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2) + '\n')

console.log(JSON.stringify({
  launcher: LAUNCHER,
  generatedPatch: path.join(PKG_DIR, 'cordis.patch.yml'),
  profile: PROFILE,
  profileBackup: pkgBackup,
  next: [
    'cd ' + PROFILE + ' && pnpm install',
    'restart DSH',
    'optional: node bin/check.mjs'
  ]
}, null, 2))
